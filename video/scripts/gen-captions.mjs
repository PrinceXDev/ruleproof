// Builds SRT/VTT captions and the timing / asset manifests from timeline.json + src/generated/vo.json.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const TL = JSON.parse(fs.readFileSync(path.join(ROOT, 'timeline.json'), 'utf8'));
const VO = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/generated/vo.json'), 'utf8'));
const CUES = JSON.parse(fs.readFileSync(path.join(ROOT, 'cues.json'), 'utf8'));
const FPS = TL.fps;
const OUT = path.join(ROOT, 'out', 'captions');
fs.mkdirSync(OUT, {recursive: true});
fs.mkdirSync(path.join(ROOT, 'out', 'manifests'), {recursive: true});

const chunk = (words) => {
  const out = [];
  let cur = [];
  words.forEach((w, i) => {
    cur.push(w);
    if (/[.?!]$/.test(w.w) || (/,$/.test(w.w) && cur.length >= 4) || cur.length >= 8 || i === words.length - 1) {
      out.push(cur);
      cur = [];
    }
  });
  return out;
};
const ts = (s, sep) => {
  const ms = Math.round(s * 1000);
  const p = (n, l = 2) => String(n).padStart(l, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)}${sep}${p(ms % 1000, 3)}`;
};

function build(name, clips) {
  const cues = [];
  for (const c of clips) {
    const base = c.at / FPS;
    for (const g of chunk(c.words)) cues.push({from: base + g[0].s, to: base + g[g.length - 1].e + 0.25, text: g.map((w) => w.w).join(' ')});
  }
  cues.sort((a, b) => a.from - b.from);
  fs.writeFileSync(path.join(OUT, `${name}.srt`), cues.map((c, i) => `${i + 1}\n${ts(c.from, ',')} --> ${ts(c.to, ',')}\n${c.text}\n`).join('\n'));
  fs.writeFileSync(path.join(OUT, `${name}.vtt`), 'WEBVTT\n\n' + cues.map((c) => `${ts(c.from, '.')} --> ${ts(c.to, '.')}\n${c.text}\n`).join('\n'));
  return cues.length;
}

const main = VO.filter((c) => TL.scenes[c.scene]).map((c) => ({...c, at: c.start}));
const long = VO.map((c) => ({...c, at: TL.long.scenes[c.scene].from + c.offset}));
const tsc = TL.teaser.scenes;
const teaser = VO.filter((c) => tsc[c.scene]).map((c) => ({...c, at: tsc[c.scene].from + (c.start - TL.scenes[c.scene].from)}));
console.log('captions', build('ruleproof-3min', long), build('ruleproof-hackathon', main), build('ruleproof-teaser', teaser));

const sec = (f) => +(f / FPS).toFixed(2);
const manifest = {
  composition: 'RuleProofHackathon',
  fps: FPS,
  size: '1920x1080',
  totalFrames: TL.total,
  durationSec: sec(TL.total),
  scenes: Object.entries(TL.scenes).map(([id, s]) => ({id, startFrame: s.from, frames: s.dur, startSec: sec(s.from), endSec: sec(s.from + s.dur), cues: Object.fromEntries(Object.entries(CUES[id]).map(([k, v]) => [k, {localFrame: v, atSec: sec(s.from + v)}]))})),
  narration: VO.map((c) => ({id: c.id, scene: c.scene, startFrame: c.start, startSec: sec(c.start), durationSec: c.durationSec, endSec: +(sec(c.start) + c.durationSec).toFixed(2), text: TL.voice.find((v) => v.id === c.id).text})),
  teaser: {composition: 'RuleProofTeaser', totalFrames: TL.teaser.total, durationSec: sec(TL.teaser.total), segments: Object.entries(TL.teaser.scenes).map(([id, s]) => ({source: id, startFrame: s.from, frames: s.dur}))},
};
fs.writeFileSync(path.join(ROOT, 'out', 'manifests', 'timing-manifest.json'), JSON.stringify(manifest, null, 2));

const list = (dir) => (fs.existsSync(path.join(ROOT, 'public', dir)) ? fs.readdirSync(path.join(ROOT, 'public', dir)).map((f) => ({file: `${dir}/${f}`, bytes: fs.statSync(path.join(ROOT, 'public', dir, f)).size})) : []);
const assets = {
  media: list('media').map((a) => ({...a, origin: a.file.endsWith('speaker.webp') ? 'presenter photo supplied by the author' : 'copied unchanged from docs/media of the RuleProof repository'})),
  fonts: list('fonts').map((a) => ({...a, origin: '@fontsource packages (Inter, Space Grotesk, JetBrains Mono), SIL OFL'})),
  audio: list('audio').map((a) => ({...a, origin: 'procedurally synthesised by scripts/gen-score.mjs (original, no samples)'})),
  narration: list('vo').filter((a) => a.bytes > 0).map((a) => ({...a, origin: 'Windows System.Speech voice "Microsoft David Desktop", generated by scripts/gen-vo.py'})),
  data: [
    {file: 'src/generated/partial-fix.json', origin: 'real output of `ruleproof-ci -fixture partial -bypass -json` (12 checks, 27 attempts, 9 leaked)'},
    {file: 'src/generated/vo.json', origin: 'narration timings and loudness envelope'},
  ],
};
fs.writeFileSync(path.join(ROOT, 'out', 'manifests', 'asset-manifest.json'), JSON.stringify(assets, null, 2));
